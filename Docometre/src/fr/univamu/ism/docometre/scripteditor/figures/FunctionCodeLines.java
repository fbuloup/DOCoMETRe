package fr.univamu.ism.docometre.scripteditor.figures;

import java.util.ArrayList;
import java.util.List;

/**
 * Extracts the lines of code displayed in a function block : comments and empty lines are removed,
 * remaining lines are trimmed and at most MAX_LINES lines are kept. When code has more than MAX_LINES lines, 
 * the last displayed line is replaced by ELLIPSIS.
 */
public final class FunctionCodeLines {
	
	public static final int MAX_LINES = 3;
	public static final String ELLIPSIS = "...";
	
	public enum Language {
		ADBASIC,	// Comments : REM at line start or ' - Strings : "..."
		ARDUINO,	// Comments : // or /* ... */ - Strings : "..." or '...' with \ escape
		MATLAB,		// Comments : % or %{ ... %} (alone on their lines) - Strings : "..." or '...' (' may be the transpose operator)
		PYTHON,		// Comments : # - Strings : "..." or '...' with \ escape
		UNKNOWN		// Comments are not removed
	}
	
	private FunctionCodeLines() {
	}
	
	/**
	 * Returns the lines to display
	 * @param code the code generated by the function
	 * @param language the language of this code
	 * @return between 0 and MAX_LINES lines
	 */
	public static List<String> getDisplayedLines(String code, Language language) {
		List<String> lines = getCodeLines(code, language);
		if(lines.size() <= MAX_LINES) return lines;
		List<String> displayedLines = new ArrayList<>(lines.subList(0, MAX_LINES - 1));
		displayedLines.add(ELLIPSIS);
		return displayedLines;
	}
	
	/**
	 * Returns all the lines of code without comments and empty lines
	 * @param code the code
	 * @param language the language of this code
	 * @return the trimmed lines of code
	 */
	public static List<String> getCodeLines(String code, Language language) {
		List<String> codeLines = new ArrayList<>();
		if(code == null || code.isEmpty()) return codeLines;
		if(language == null) language = Language.UNKNOWN;
		boolean[] inBlockComment = new boolean[] {false};
		for (String line : code.split("\\R")) {
			String codeLine = removeComments(line, language, inBlockComment).trim();
			if(!codeLine.isEmpty()) codeLines.add(codeLine);
		}
		return codeLines;
	}
	
	/*
	 * Returns the line without its comments. inBlockComment is the state of a block comment, 
	 * updated as it may span several lines.
	 */
	private static String removeComments(String line, Language language, boolean[] inBlockComment) {
		if(language == Language.UNKNOWN) return line;
		if(language == Language.MATLAB) {
			String trimmedLine = line.trim();
			if(inBlockComment[0]) {
				if(trimmedLine.equals("%}")) inBlockComment[0] = false;
				return "";
			}
			if(trimmedLine.equals("%{")) {
				inBlockComment[0] = true;
				return "";
			}
		}
		StringBuilder codeLine = new StringBuilder();
		char quote = 0;
		int i = 0;
		while (i < line.length()) {
			char c = line.charAt(i);
			char next = i + 1 < line.length() ? line.charAt(i + 1) : 0;
			if(inBlockComment[0]) {
				// Only ARDUINO block comments can be here
				if(c == '*' && next == '/') {
					inBlockComment[0] = false;
					codeLine.append(' ');
					i++;
				}
				i++;
				continue;
			}
			if(quote != 0) {
				codeLine.append(c);
				if(c == quote && next == quote) {
					// Doubled quote : escaped quote (ADbasic, Matlab) or concatenation of two strings, still in string
					codeLine.append(next);
					i++;
				} else if(c == '\\' && next != 0 && (language == Language.ARDUINO || language == Language.PYTHON)) {
					codeLine.append(next);
					i++;
				} else if(c == quote) quote = 0;
				i++;
				continue;
			}
			if(isLineCommentStart(line, i, language, codeLine)) break;
			if(language == Language.ARDUINO && c == '/' && next == '*') {
				inBlockComment[0] = true;
				i += 2;
				continue;
			}
			if(isStringStart(c, language, codeLine)) quote = c;
			codeLine.append(c);
			i++;
		}
		return codeLine.toString();
	}
	
	private static boolean isLineCommentStart(String line, int index, Language language, StringBuilder previousCode) {
		char c = line.charAt(index);
		switch (language) {
		case ADBASIC:
			if(c == '\'') return true;
			if(previousCode.toString().trim().isEmpty() && line.regionMatches(true, index, "REM", 0, 3)) 
				return index + 3 == line.length() || Character.isWhitespace(line.charAt(index + 3));
			return false;
		case ARDUINO:
			return c == '/' && index + 1 < line.length() && line.charAt(index + 1) == '/';
		case MATLAB:
			return c == '%';
		case PYTHON:
			return c == '#';
		default:
			return false;
		}
	}
	
	private static boolean isStringStart(char c, Language language, StringBuilder previousCode) {
		if(c == '"') return true;
		if(c != '\'') return false;
		if(language == Language.ARDUINO || language == Language.PYTHON) return true;
		if(language == Language.MATLAB) {
			// ' is the transpose operator when it follows a variable, a closing bracket, a dot or another transpose operator
			if(previousCode.length() == 0) return true;
			char previous = previousCode.charAt(previousCode.length() - 1);
			return !(Character.isLetterOrDigit(previous) || previous == '_' || previous == ')' || previous == ']' 
					|| previous == '}' || previous == '.' || previous == '\'');
		}
		return false;
	}
	
}
