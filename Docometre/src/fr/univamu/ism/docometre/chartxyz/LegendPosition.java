package fr.univamu.ism.docometre.chartxyz;

/**
 * Position de la légende dans les graphes 1D et 2D.
 */
public enum LegendPosition {
    /** Dans la zone de tracé, en haut à gauche, sur fond semi-transparent (par défaut). */
    INSIDE,
    /** En ligne(s) tout en bas, sous les graduations de l'axe des abscisses (hors de la zone de tracé). */
    BELOW
}
