package fr.univamu.ism.docometre.chartxyz;

/**
 * Position of the legend in the 1D and 2D charts.
 */
public enum LegendPosition {
    /** In the plot area, at the top left, on a semi-transparent background. */
    INSIDE,
    /** In row(s) at the very bottom, below the abscissa tick labels (outside the plot area, default). */
    BELOW
}
