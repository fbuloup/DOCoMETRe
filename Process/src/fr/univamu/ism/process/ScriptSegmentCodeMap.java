package fr.univamu.ism.process;

import java.util.IdentityHashMap;
import java.util.Map;

/**
 * Links the blocks of a script segment to the lines of the code generated for this segment.
 * It is built by the script each time the code of a segment is generated (INITIALIZE, LOOP or FINALIZE
 * step) and is used to go from a block or a connection of the diagram to the corresponding line in
 * the source code. Line numbers are zero based and relative to the first line of the segment code.
 */
public class ScriptSegmentCodeMap {
	
	private ScriptSegmentType segmentType;
	
	// Generation index : the greater, the later this code has been generated
	private long generationIndex;
	
	// Segment code as inserted in the source code (i.e. after indentation)
	private String code = "";
	
	// Block -> {first line, last line} of the code generated by this block
	private Map<Block, int[]> blocksLines = new IdentityHashMap<>();
	
	// IF block -> line where the false branch starts (ELSE line when the target language has one)
	private Map<Block, Integer> elseLines = new IdentityHashMap<>();
	
	// IF block -> line ending the IF block (ENDIF) ; DO block -> line ending the loop (UNTIL)
	private Map<Block, int[]> closingLines = new IdentityHashMap<>();
	
	// Raw offsets recorded during generation, converted to lines when generation is done 
	private transient Map<Block, int[]> blocksOffsets = new IdentityHashMap<>();
	private transient Map<Block, Integer> elseOffsets = new IdentityHashMap<>();
	private transient Map<Block, int[]> closingOffsets = new IdentityHashMap<>();
	
	ScriptSegmentCodeMap(ScriptSegmentType segmentType) {
		this.segmentType = segmentType;
	}
	
	public ScriptSegmentType getSegmentType() {
		return segmentType;
	}
	
	public long getGenerationIndex() {
		return generationIndex;
	}
	
	public String getCode() {
		return code;
	}
	
	/*
	 * Recording methods, called during code generation with offsets in the raw segment code.
	 * A block generated several times keeps its first location.
	 */
	void recordBlock(Block block, int startOffset, int endOffset) {
		if(block != null && !blocksOffsets.containsKey(block)) blocksOffsets.put(block, new int[] {startOffset, endOffset});
	}
	
	void recordElse(Block block, int offset) {
		if(block != null && !elseOffsets.containsKey(block)) elseOffsets.put(block, offset);
	}
	
	void recordClosing(Block block, int startOffset, int endOffset) {
		if(block != null && !closingOffsets.containsKey(block)) closingOffsets.put(block, new int[] {startOffset, endOffset});
	}
	
	/*
	 * Converts recorded offsets to lines using the raw generated code.
	 * Indentation done afterward keeps lines one to one, so these lines are still valid in the indented code.
	 */
	void complete(String rawCode, String finalCode, long generationIndex) {
		this.generationIndex = generationIndex;
		code = finalCode == null ? "" : finalCode;
		rawCode = rawCode == null ? "" : rawCode;
		for (Map.Entry<Block, int[]> entry : blocksOffsets.entrySet()) blocksLines.put(entry.getKey(), toLines(rawCode, entry.getValue()[0], entry.getValue()[1]));
		for (Map.Entry<Block, Integer> entry : elseOffsets.entrySet()) elseLines.put(entry.getKey(), toLines(rawCode, entry.getValue(), entry.getValue())[0]);
		for (Map.Entry<Block, int[]> entry : closingOffsets.entrySet()) closingLines.put(entry.getKey(), toLines(rawCode, entry.getValue()[0], entry.getValue()[1]));
		blocksOffsets.clear();
		elseOffsets.clear();
		closingOffsets.clear();
	}
	
	/*
	 * Returns first and last lines of the non blank text between start and end offsets.
	 * If this text is blank, the line of the next non blank character is returned.
	 */
	private static int[] toLines(String code, int startOffset, int endOffset) {
		startOffset = Math.max(0, Math.min(startOffset, code.length()));
		endOffset = Math.max(startOffset, Math.min(endOffset, code.length()));
		int first = startOffset;
		while(first < endOffset && Character.isWhitespace(code.charAt(first))) first++;
		if(first == endOffset) {
			// Blank text : go to next non blank character
			while(first < code.length() && Character.isWhitespace(code.charAt(first))) first++;
			int line = lineOf(code, Math.min(first, code.length()));
			return new int[] {line, line};
		}
		int last = endOffset - 1;
		while(last > first && Character.isWhitespace(code.charAt(last))) last--;
		return new int[] {lineOf(code, first), lineOf(code, last)};
	}
	
	private static int lineOf(String code, int offset) {
		int line = 0;
		for (int i = 0; i < offset && i < code.length(); i++) if(code.charAt(i) == '\n') line++;
		return line;
	}
	
	/**
	 * Returns the number of lines of the segment code
	 * @return the number of lines
	 */
	public int getLinesNumber() {
		if(code.isEmpty()) return 0;
		int linesNumber = lineOf(code, code.length());
		// Last line without line delimiter
		if(!code.endsWith("\n")) linesNumber++;
		return linesNumber;
	}
	
	/**
	 * Returns the block whose code contains a line : the block generating this line, or the IF or DO block 
	 * this line belongs to (ELSE, ENDIF, UNTIL...). If several blocks contain this line, the block 
	 * with the smallest lines range is returned.
	 * @param line the line, zero based, relative to the first line of the segment code
	 * @return the block or null if this line does not belong to any block
	 */
	public Block getBlockAtLine(int line) {
		Block foundBlock = null;
		int foundRange = Integer.MAX_VALUE;
		for (Map.Entry<Block, int[]> entry : blocksLines.entrySet()) {
			int[] lines = entry.getValue();
			if(line >= lines[0] && line <= lines[1] && lines[1] - lines[0] < foundRange) {
				foundBlock = entry.getKey();
				foundRange = lines[1] - lines[0];
			}
		}
		for (Map.Entry<Block, int[]> entry : closingLines.entrySet()) {
			int[] lines = entry.getValue();
			if(line >= lines[0] && line <= lines[1] && lines[1] - lines[0] < foundRange) {
				foundBlock = entry.getKey();
				foundRange = lines[1] - lines[0];
			}
		}
		for (Map.Entry<Block, Integer> entry : elseLines.entrySet()) {
			if(line == entry.getValue() && foundRange > 0) {
				foundBlock = entry.getKey();
				foundRange = 0;
			}
		}
		return foundBlock;
	}
	
	public boolean contains(Block block) {
		return blocksLines.containsKey(block);
	}
	
	/**
	 * Returns first and last lines of the code generated by this block.
	 * For a DO block, it is the line opening the loop ; use {@link #getClosingLines(Block)} to get the line closing the loop.  
	 * @param block the block
	 * @return {first line, last line} or null if this block has not been generated in this segment
	 */
	public int[] getBlockLines(Block block) {
		int[] lines = blocksLines.get(block);
		return lines == null ? null : lines.clone();
	}
	
	/**
	 * Returns first and last lines of the code closing this IF or DO block (ENDIF, UNTIL...)
	 * @param block the IF or DO block
	 * @return {first line, last line} or null if not available
	 */
	public int[] getClosingLines(Block block) {
		int[] lines = closingLines.get(block);
		return lines == null ? null : lines.clone();
	}
	
	/**
	 * Returns the lines corresponding to a connection between two blocks :
	 * <ul>
	 * <li>branch of an IF block going directly to its end block (empty branch) : ELSE line for the true branch, ENDIF line for the false branch,</li>
	 * <li>connection from the last block of a DO block to this DO block : line closing the loop (UNTIL...),</li>
	 * <li>otherwise : lines of the target block, or lines of the source block if the target block has not been generated.</li>
	 * </ul>
	 * @param sourceBlock the source block of the connection
	 * @param targetBlock the target block of the connection
	 * @return {first line, last line} or null if not available
	 */
	public int[] getConnectionLines(Block sourceBlock, Block targetBlock) {
		if(sourceBlock instanceof IfBlock) {
			IfBlock ifBlock = (IfBlock) sourceBlock;
			Block endBlock = ifBlock.getEndBlock();
			if(endBlock != null && targetBlock == endBlock) {
				if(targetBlock == ifBlock.getNextTrueBranchBlock() && elseLines.containsKey(ifBlock)) {
					int line = elseLines.get(ifBlock);
					return new int[] {line, line};
				}
				if(targetBlock == ifBlock.getNextFalseBranchBlock() && closingLines.containsKey(ifBlock)) return getClosingLines(ifBlock);
			}
		}
		if(targetBlock instanceof DoBlock && sourceBlock != null && sourceBlock.isLastBlockOf((DoBlock) targetBlock)) {
			int[] lines = getClosingLines(targetBlock);
			if(lines != null) return lines;
		}
		int[] lines = getBlockLines(targetBlock);
		if(lines == null) lines = getBlockLines(sourceBlock);
		return lines;
	}

}
